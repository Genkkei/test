import { z } from 'zod'

/*
 * Отпечаток сайта (навык site-craft): то, что делает сайт непохожим на остальные 121. Владелец, 24.10:
 * «каждый сайт должен быть абсолютно уникальным: свои элементы, свой шрифт, свои анимации».
 * scripts/craft-check.mjs не пускает в каталог два сайта с одинаковым display-шрифтом, раскладкой первого экрана,
 * ведущим приёмом движения или шаблоном. Поля — для людей и проверки; рисует всё сам шаблон.
 */
const word = z.string().regex(/^[a-z0-9-]{2,40}$/)
export const craftSchema = z.object({
  /** замысел одной фразой: из чего сделан сайт */
  concept: z.string().min(8).max(200),
  /** шрифт меток и мелких подписей (моно/узкий капс); display и body — в theme */
  label: z.string().default(''),
  /** раскладка первого экрана — уникальна в каталоге */
  skeleton: word,
  /** ведущий приём движения — уникален в каталоге */
  signature: word,
  /** порядок входа первого экрана */
  sequence: z.array(word).min(2).max(8),
  /** своя кривая: четыре числа cubic-bezier */
  ease: z.string().regex(/^-?[0-9.]+,\s*-?[0-9.]+,\s*-?[0-9.]+,\s*-?[0-9.]+$/),
  /** форма «предмета» вместо карточек: билет, бирка, табло, полка… */
  surface: word,
})
export type Craft = z.infer<typeof craftSchema>
